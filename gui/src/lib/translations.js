/** Map any BCP-47 tag (e.g. from `navigator.language`) to a supported locale. */
export function normalizeLocale(value) {
  if (!value) return null;
  const v = String(value).toLowerCase();
  if (v.startsWith("es")) return "es-ES";
  for (const code of ["fr", "it", "de", "nl", "en"]) {
    if (v === code || v.startsWith(code + "-")) return code;
  }
  return null;
}

